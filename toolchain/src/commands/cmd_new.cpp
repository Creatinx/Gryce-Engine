int cmd_new(const Options& o) {
    if (o.positionals.empty()) return usage();

    const fs::path dir(o.positionals.front());
    const bool force = o.is_flag("force");

    std::error_code ec;
    if (fs::exists(dir, ec) && !fs::is_directory(dir, ec)) {
        std::fprintf(stderr, "[错误] %s 已存在且不是目录\n", dir.string().c_str());
        return 1;
    }
    if (fs::is_directory(dir, ec) && !force) {
        // 只允许空目录；非空时列出条目数，提示用 --force
        std::size_t count = 0;
        for (fs::directory_iterator it(dir, ec), end; !ec && it != end; it.increment(ec)) {
            if (it->path().filename() != "." && it->path().filename() != "..") ++count;
        }
        if (count > 0) {
            std::fprintf(stderr,
                         "[错误] 目录非空（%zu 项）：%s\n"
                         "       换一个目录，或加 --force 覆盖同名文件\n",
                         count, dir.string().c_str());
            return 1;
        }
    }

    std::string name = o.get("name");
    if (name.empty()) {
        name = dir.filename().string();
        if (name.empty() || name == "." || name == "..") name = "GryceProject";
    }

    int width = o.get_int("width", 1280);
    int height = o.get_int("height", 720);
    if (width < 64) width = 64;
    if (height < 64) height = 64;

    std::string api = o.get("api", "opengl");
    if (api != "opengl" && api != "vulkan" && api != "dx12") {
        std::fprintf(stderr, "[错误] --api 只支持 opengl|vulkan|dx12（收到 '%s'）\n", api.c_str());
        return 1;
    }

    const bool with_extension = o.is_flag("extension");

    mkdir_p(dir);
    mkdir_p(dir / "scenes");
    mkdir_p(dir / "models");

    std::vector<std::string> created;
    std::vector<std::string> kept;
    bool ok = true;

    ok = write_text(dir / "project.data", make_project_data(name, width, height, api), force, created, kept) && ok;
    ok = write_text(dir / "scenes" / "main.gesc", make_scene(name), force, created, kept) && ok;
    ok = write_text(dir / "models" / "cube.obj", make_cube_obj(), force, created, kept) && ok;
    std::string main_js = replace_all(kMainJs, "__PROJECT_NAME__", js_escape_single_quoted(name));
    main_js = replace_all(main_js, "__WIDTH__", std::to_string(width));
    main_js = replace_all(main_js, "__HEIGHT__", std::to_string(height));
    ok = write_text(dir / "main.js", main_js, force, created, kept) && ok;
    ok = write_text(dir / "README.md", make_readme(name, api, with_extension), force, created, kept) && ok;
    if (with_extension) {
        ok = write_text(dir / "extension.cpp", kExtensionCpp, force, created, kept) && ok;
    }

    if (!ok) {
        std::fprintf(stderr, "[错误] 写文件失败（目录权限？）：%s\n", dir.string().c_str());
        return 1;
    }

    std::printf("[完成] 项目已创建：%s（name=%s, api=%s, %dx%d）\n",
                dir.string().c_str(), name.c_str(), api.c_str(), width, height);
    for (const std::string& p : created) std::printf("  + %s\n", p.c_str());
    for (const std::string& p : kept) std::printf("  = %s（已存在，跳过）\n", p.c_str());
    std::printf("下一步：\n");
    std::printf("  cmake --build build --target GryceApp\n");
    std::printf("  build/GryceApp.exe --project %s\n", dir.string().c_str());
    std::printf("  GryceGC package --build-dir build --project %s --name %s --verify\n",
                dir.string().c_str(), name.c_str());
    return 0;
}

