// GryceGC new：创建项目骨架
//
// 用法: GryceGC new <dir> [options]
// 选项:
//   --name <name>       项目显示名（默认取目录名）
//   --width / --height  默认窗口尺寸（默认 1280x720）
//   --api <api>         默认渲染后端 opengl|vulkan|dx12（默认 opengl）
//   --extension         同时生成 extension.cpp 模板
//   --force             目标目录非空也继续（覆盖同名文件，保留其它文件）
//
// 产物（每个项目只需这些，不再需要自己的 main.cpp）：
//   main.js            入口脚本：建窗、载场景、飞行相机、Esc 退出
