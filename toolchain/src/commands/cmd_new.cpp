// ---------------------------------------------------------------------------
// JSON 字符串转义（只处理会破坏 JSON 的字符；项目名一般是 ASCII / 中文）
// ---------------------------------------------------------------------------
std::string json_escape(const std::string& s) {
    std::string out;
    out.reserve(s.size() + 8);
    for (unsigned char c : s) {
        switch (c) {
            case '"': out += "\\\""; break;
            case '\\': out += "\\\\"; break;
            case '\n': out += "\\n"; break;
            case '\r': out += "\\r"; break;
            case '\t': out += "\\t"; break;
            default:
                if (c < 0x20) {
                    char buf[8];
                    std::snprintf(buf, sizeof(buf), "\\u%04x", c);
                    out += buf;
                } else {
                    out += static_cast<char>(c);
                }
        }
    }
    return out;
}

std::string replace_all(std::string s, const std::string& from, const std::string& to) {
    if (from.empty()) return s;
    std::size_t pos = 0;
    while ((pos = s.find(from, pos)) != std::string::npos) {
        s.replace(pos, from.size(), to);
        pos += to.size();
    }
    return s;
}

// 项目名要嵌进 main.js 的单引号字符串，转义反斜杠、单引号与换行。
std::string js_escape_single_quoted(const std::string& s) {
    std::string out;
    out.reserve(s.size() + 8);
    for (char c : s) {
        switch (c) {
            case '\\': out += "\\\\"; break;
            case '\'': out += "\\'"; break;
            case '\n': out += "\\n"; break;
            case '\r': break;
            default: out += c;
        }
    }
    return out;
}

// ---------------------------------------------------------------------------
// 单位立方体 OBJ（每面独立顶点，保证平面法线正确）
//
// 面顺序：对每个轴 a（x/y/z）取 ±法线，先取 +a 再取 -a。四个角点的绕序为
// (-u,-w) (+u,-w) (+u,+w) (-u,+w)，其中 (u × w) = 外法线，因此从外侧看是
// 逆时针，与引擎的 CCW 正面约定一致。
// ---------------------------------------------------------------------------
std::string make_cube_obj() {
    struct Vec3 {
        float x, y, z;
    };
    auto e = [](int axis) -> Vec3 {
        Vec3 v{0.0f, 0.0f, 0.0f};
        (axis == 0 ? v.x : axis == 1 ? v.y : v.z) = 1.0f;
        return v;
    };
    auto scale = [](const Vec3& v, float s) { return Vec3{v.x * s, v.y * s, v.z * s}; };
    auto add = [](const Vec3& a, const Vec3& b) { return Vec3{a.x + b.x, a.y + b.y, a.z + b.z}; };
    auto sub = [](const Vec3& a, const Vec3& b) { return Vec3{a.x - b.x, a.y - b.y, a.z - b.z}; };

    struct Quad {
        Vec3 n;
        Vec3 v[4];
    };
    std::vector<Quad> quads;
    quads.reserve(6);

    for (int axis = 0; axis < 3; ++axis) {
        for (int sign = -1; sign <= 1; sign += 2) {
            Quad q{};
            q.n = scale(e(axis), static_cast<float>(sign));
            // 让 u × w = n：+e_a 时 u = -e_{a+2}, w = +e_{a+1}；-e_a 时 u 取反。
            Vec3 u = scale(e((axis + 2) % 3), -1.0f);
            Vec3 w = e((axis + 1) % 3);
            if (sign < 0) u = scale(u, -1.0f);

            const Vec3 center = scale(q.n, 0.5f);
            const Vec3 uh = scale(u, 0.5f);
            const Vec3 wh = scale(w, 0.5f);
            q.v[0] = sub(sub(center, uh), wh);
            q.v[1] = sub(add(center, uh), wh);
            q.v[2] = add(add(center, uh), wh);
            q.v[3] = add(sub(center, uh), wh);
            quads.push_back(q);
        }
    }

    std::string obj;
    obj += "# Unit cube, 1x1x1 centered at origin (half extent 0.5)\n";
    obj += "# generated by GryceGC new - CCW front faces\n";
    for (const Quad& q : quads) {
        for (const Vec3& v : q.v) {
            char buf[96];
            std::snprintf(buf, sizeof(buf), "v %.6f %.6f %.6f\n",
                          static_cast<double>(v.x), static_cast<double>(v.y),
                          static_cast<double>(v.z));
            obj += buf;
        }
    }
    // 每个角点各一份 uv 与法线：引擎的 OBJ 载入器按 v/vt/vn 三元组取顶点，
    // 写成 v//vn 会丢掉法线（焊点后法线退化为 0，光照全黑）。
    const char* kUv[4] = {"0.000000 0.000000", "1.000000 0.000000",
                          "1.000000 1.000000", "0.000000 1.000000"};
    for (int i = 0; i < 6; ++i) {
        for (int c = 0; c < 4; ++c) obj += std::string("vt ") + kUv[c] + "\n";
    }
    for (int i = 0; i < 6; ++i) {
        for (int c = 0; c < 4; ++c) {
            char buf[96];
            std::snprintf(buf, sizeof(buf), "vn %.6f %.6f %.6f\n",
                          static_cast<double>(quads[static_cast<std::size_t>(i)].n.x),
                          static_cast<double>(quads[static_cast<std::size_t>(i)].n.y),
                          static_cast<double>(quads[static_cast<std::size_t>(i)].n.z));
            obj += buf;
        }
    }
    for (int i = 0; i < 6; ++i) {
        const int b = i * 4 + 1;   // OBJ 索引从 1 开始，四个角点共享同一法线
        char buf[128];
        std::snprintf(buf, sizeof(buf), "f %d/%d/%d %d/%d/%d %d/%d/%d %d/%d/%d\n",
                      b, b, b, b + 1, b + 1, b + 1,
                      b + 2, b + 2, b + 2, b + 3, b + 3, b + 3);
        obj += buf;
    }
    return obj;
}

